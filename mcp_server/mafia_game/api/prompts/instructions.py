def role_instruction(role: str, phase: str) -> str:
    """검증된 본인 역할과 현재 단계에 해당하는 전략만 조합한다."""

    if role not in ROLE_PLANS or phase not in DISCUSSION_PHASES | VOTE_PHASES | {"NIGHT_ACTION"}:
        raise ValueError("역할 또는 게임 단계가 올바르지 않습니다.")
    plan = ROLE_PLANS[role]
    if phase in DISCUSSION_PHASES:
        action = (
            "전체 공개 이력에서 자신의 이전 입장과 남은 질문을 확인하고 "
            "본인에게 온 말의 핵심부터 받는다. "
            "답변·반박·의도적인 회피 중 역할에 유리한 반응을 고르되 "
            "질문을 못 본 듯 새 질문만 던지지 않는다. "
            "한 번에 쟁점 하나와 대화 목적 하나를 고른다. 의심 대상과 설득할 사람을 구분하고, "
            "추궁뿐 아니라 짧은 인정·방어·조건부 동의로 협력할 여지도 남긴다. "
            "이미 답한 질문을 표현만 바꿔 반복하지 않고 "
            "상대가 답할 기회도 없었던 침묵을 회피로 몰지 않는다. "
            "처형 결과·새 반증으로 기존 판단이 깨지면 의심 순위를 다시 비교한다. "
            "전략의 전체 과정을 대사에 해설하지 않는다. "
            "마감이 가까우면 새 논점을 늘리기보다 자신의 후보와 핵심 이유를 정한다. "
            "첫날이 아닌 토론에서만 새로 보탤 답·주장·반론이 없으면 PASS한다. "
            "공개 대사에는 이름·좌석을 쓰고 UUID를 쓰지 않는다. "
            "자신의 좌석을 타인처럼 지목하지 않는다. "
        )
        if phase == "DAY_DISCUSSION":
            action += (
                " 첫날 낮(public.data.game.day_number=1, round=0)은 인간·AI 모두 PASS 금지이며 "
                "반드시 짧은 SPEAK를 한다. "
                "첫 발언은 실제 공개 발언에 대한 반응이나 "
                "새 확인 질문·판단 기준을 1~2문장으로 낸다. "
                "제공되지 않은 알리바이·관찰을 요구하거나 빈 배경 이야기를 채우지 않는다. "
                "이후에도 인사·동의만 되풀이하지 말고 아직 다루지 않은 관점이나 새 반응을 보탠다."
            )
        detail = plan["discussion"]
    elif phase in VOTE_PHASES:
        action = (
            "기권 없이 turn.data.valid_targets의 한 player_id를 선택한다. "
            "첫 후보나 좌석 순서로 고르지 않는다. 공개 득표수로 개별 표를 추정하지 않는다. "
            "재투표는 현재 허용 후보 안에서 다시 비교한다. 역할의 승리 목표를 기준으로 "
            "자신의 발언과 실제 선택의 일관성·변경 이득을 함께 판단한다."
        )
        detail = plan["vote"]
    else:
        action = (
            "밤에는 turn.data.allowed_tools가 허용한 본인 능력만 사용한다. 행동이 허용된 경우 "
            "기권 없이 turn.data.valid_targets의 한 player_id를 선택한다. "
            "실제 허용 대상과 마감은 turn.data가 우선이다."
        )
        detail = plan["night"]
    final = (
        "다섯 번째 밤 뒤 마지막 판단이다. "
        "다음 답변을 기다리지 말고 현재 근거로 최종 후보와 입장을 정한다."
        if phase in {"FINAL_DISCUSSION", "FINAL_ACCUSATION"} else ""
    )
    return "\n".join(filter(None, (
        f"역할: {role}", plan["goal"], EVIDENCE_GUIDE, detail, action, final,
    )))


